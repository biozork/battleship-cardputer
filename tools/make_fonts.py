"""Turns the TTF fonts in tools/fonts into smooth fonts the Cardputer can draw.

M5GFX can draw "VLW" fonts: every letter is stored as a small greyscale
picture, so the edges come out smooth. This script renders each letter with
Pillow and writes them as byte arrays into src/fonts.h, which gets built into
the firmware.

Run it again after changing a size below:
    python tools/make_fonts.py              writes src/fonts.h
    python tools/make_fonts.py preview.png  also draws a sample sheet (for checking sizes)

Needs Pillow (pip install pillow). Both fonts are under the SIL Open Font
License; see the OFL-*.txt files next to them.
"""
import os
import struct
import sys

from PIL import Image, ImageDraw, ImageFont

HERE = os.path.dirname(os.path.abspath(__file__))
FONT_DIR = os.path.join(HERE, "fonts")
OUT = os.path.join(HERE, "..", "src", "fonts.h")

ASCII = "".join(chr(c) for c in range(32, 127))
COORD = "ABCDEFGHIJ0123456789"
CAPS = " ABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789!.-:"

# name in C, font file, weight (variable fonts only), size in pixels, letters to include
FONTS = [
    ("FONT_BODY", "AtkinsonHyperlegible-Regular.ttf", None, 12, ASCII),
    ("FONT_BOLD", "AtkinsonHyperlegible-Bold.ttf", None, 12, ASCII),
    ("FONT_SMALL", "AtkinsonHyperlegible-Bold.ttf", None, 10, ASCII),
    ("FONT_HEAD", "PixelifySans.ttf", b"Bold", 14, ASCII),
    ("FONT_LOGO", "PixelifySans.ttf", b"Bold", 18, CAPS),
    ("FONT_BIG", "PixelifySans.ttf", b"Bold", 24, COORD),
    ("FONT_BANNER", "PixelifySans.ttf", b"Bold", 20, CAPS),
    ("FONT_TITLE", "PixelifySans.ttf", b"Bold", 30, CAPS),
]


def load(file, weight, size):
    font = ImageFont.truetype(os.path.join(FONT_DIR, file), size)
    if weight:
        font.set_variation_by_name(weight)
    return font


def glyphs(font, chars):
    """Each letter as (code, width, height, advance, top, left, alpha bytes)."""
    out = []
    for ch in sorted(set(chars)):
        x0, y0, x1, y1 = font.getbbox(ch, anchor="ls")  # relative to the baseline
        w, h = max(0, x1 - x0), max(0, y1 - y0)
        pixels = b""
        if w and h:
            img = Image.new("L", (w, h), 0)
            ImageDraw.Draw(img).text((-x0, -y0), ch, font=font, fill=255, anchor="ls")
            pixels = img.tobytes()
        out.append((ord(ch), w, h, round(font.getlength(ch)), -y0, x0, pixels))
    return out


def vlw(font, size, chars):
    """The VLW file format: a header, then each letter's size, then all the pictures."""
    ascent, descent = font.getmetrics()
    gs = glyphs(font, chars)
    data = struct.pack(">6i", len(gs), 11, size, 0, ascent, descent)
    for code, w, h, adv, top, left, _ in gs:
        data += struct.pack(">7i", code, h, w, adv, top, left, 0)
    for g in gs:
        data += g[6]
    return data, gs, ascent


def write_header(blobs):
    lines = [
        "// Generated by tools/make_fonts.py; do not edit by hand.",
        "// Smooth (VLW) fonts: Atkinson Hyperlegible and Pixelify Sans, SIL Open Font License.",
        "#pragma once",
        "#include <Arduino.h>",
        "",
    ]
    for name, data in blobs:
        lines.append(f"static const uint8_t {name}[] PROGMEM = {{  // {len(data)} bytes")
        for i in range(0, len(data), 24):
            lines.append("  " + ",".join(str(b) for b in data[i:i + 24]) + ",")
        lines.append("};")
        lines.append("")
    with open(OUT, "w", newline="\n") as f:
        f.write("\n".join(lines))


def draw_text(img, gs, x, baseline, text, col):
    """Draws text the way the device will, from the generated letters."""
    table = {g[0]: g for g in gs}
    for ch in text:
        g = table.get(ord(ch))
        if not g:
            continue
        code, w, h, adv, top, left, pixels = g
        for j in range(h):
            for i in range(w):
                a = pixels[j * w + i] / 255
                px, py = x + left + i, baseline - top + j
                if 0 <= px < img.width and 0 <= py < img.height and a:
                    bg = img.getpixel((px, py))
                    img.putpixel((px, py), tuple(int(b + (c - b) * a) for b, c in zip(bg, col)))
        x += adv


def preview(path, made):
    img = Image.new("RGB", (240, 135), (10, 22, 30))
    y = 4
    samples = {
        "FONT_BODY": "Partner fires first. B7: miss.",
        "FONT_BOLD": "you fire first! sunk Cruiser!",
        "FONT_SMALL": "A B C D E F G H I J  1 2 10  tab ok",
        "FONT_HEAD": "PLACE FLEET  YOUR TURN",
        "FONT_LOGO": "BATTLESHIP",
        "FONT_BIG": "B7 J10",
        "FONT_BANNER": "SUNK!",
        "FONT_TITLE": "YOU WIN!",
    }
    for name, (gs, ascent) in made.items():
        y += ascent
        draw_text(img, gs, 4, y, samples[name], (232, 238, 240))
        y += 3
    img.resize((960, 540), Image.NEAREST).save(path)
    print("preview written to", path)


def main():
    blobs, made = [], {}
    for name, file, weight, size, chars in FONTS:
        font = load(file, weight, size)
        data, gs, ascent = vlw(font, size, chars)
        blobs.append((name, data))
        made[name] = (gs, ascent)
        print(f"{name}: {len(gs)} letters, {len(data)} bytes")
    write_header(blobs)
    print("wrote", os.path.normpath(OUT))
    if len(sys.argv) > 1:
        preview(sys.argv[1], made)


if __name__ == "__main__":
    main()
